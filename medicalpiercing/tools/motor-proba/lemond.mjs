// Probafoglalas lemondasa a Salonic lemondo oldalan (a Salonic oldal nyomkovetoi tiltva). node lemond.mjs <cancelBooking-URL>
import { chromium } from '../pw.mjs';
const url = process.argv[2];
if (!/^https:\/\/medicalpiercing\.salonic\.hu\/booking\/cancelBooking\/[0-9a-f-]{36}$/.test(url || '')) throw new Error('ervenytelen lemondo URL');
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1000, height: 1100 }, locale: 'hu-HU' });
const ENGEDETT = /^https:\/\/([a-z0-9.-]*salonic\.hu|cdn\.jsdelivr\.net|cdnjs\.cloudflare\.com|fonts\.(googleapis|gstatic)\.com|www\.google\.com\/recaptcha|www\.gstatic\.com\/recaptcha)\//;
await ctx.route('**/*', (route) => { const r = route.request(); if (ENGEDETT.test(r.url())) return route.continue(); return route.fulfill({ status: 200, headers: { 'content-type': 'application/json', 'access-control-allow-origin': r.headers().origin || '*' }, body: '{}' }); });
const p = await ctx.newPage();
await p.goto(url, { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(2500);
const szoveg0 = (await p.locator('body').innerText()).replace(/\s+/g, ' ');
console.log('allapot elotte:', /Visszaigazolt|Confirmed/.test(szoveg0) ? 'Visszaigazolt' : /Lemondva|lemondt|törölve|Cancelled|Canceled/i.test(szoveg0) ? 'mar lemondva' : '?', '|', szoveg0.match(/(Január|Február|Március|Április|Május|Június|Július|Augusztus|Szeptember|Október|November|December) \d+\.[^|]{0,60}/)?.[0] || '');
if (!(await p.locator('.swal-overlay--show-modal').count())) await p.getByRole('link', { name: /^\s*(Lemondom|Cancel booking)\s*$/i }).first().click();
const ok = p.locator('input[type="text"]:visible, input:not([type]):visible').last();
await ok.waitFor({ state: 'visible', timeout: 10000 });
await ok.fill('Próbafoglalás (TESZT), lemondva');
await p.getByRole('button', { name: /Igen, lemondom|Yes, I want to cancel/i }).click();
await p.waitForTimeout(3500);
const veg = (await p.locator('body').innerText()).replace(/\s+/g, ' ');
console.log(/lemondása sikeres|successfully cancel|cancel\w* (was )?successful|has been cancel+ed|törölve/i.test(veg) ? 'SIKERES: lemondás visszaigazolva' : 'NEM IGAZOLTA VISSZA: ' + veg.slice(-300));
await b.close();
